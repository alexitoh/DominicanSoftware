// Prueba de la búsqueda de módulos. Ejecutar con: node --import ./tests/stubs/registrar.mjs tests/busqueda.mjs
import assert from 'node:assert/strict';
globalThis.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
globalThis.document = { addEventListener() {}, createElement: () => ({}) };
globalThis.window = { addEventListener() {}, dispatchEvent() {} };
const { buscarModulos } = await import('../src/inicio.js');
const ids = (t, puede) => buscarModulos(t, puede).map((m) => m.id);
assert.equal(ids('vent')[0], 'ventas', 'lo que empieza con el texto va primero');
assert.ok(ids('GARANTIA').includes('garantias'), 'sin importar acentos ni mayúsculas');
assert.ok(ids('garantías').includes('garantias'));
assert.ok(ids('factura').includes('ventas'), 'por palabras relacionadas');
assert.ok(ids('respaldo').includes('ajustes'));
assert.deepEqual(ids('zzz'), []);
assert.equal(ids('').length, 13, 'sin texto salen todos los módulos');
assert.ok(ids('balance').includes('contabilidad') && ids('nomina').includes('contabilidad'), 'Contabilidad se encuentra por sus palabras');
assert.deepEqual(ids('', (id) => id === 'ventas' || id === 'inicio'), ['ventas'], 'solo los módulos con permiso');
assert.equal(ids('ajust', (id) => id !== 'ajustes').includes('ajustes'), false, 'no ofrece módulos sin permiso');
const { validarDocumento, formatearDocumento, textoDocumento } = await import('../src/fiscal.js');
assert.deepEqual(validarDocumento('rnc', '1-01-12345-6'), { tipo: 'rnc', numero: '101123456' });
assert.match(validarDocumento('rnc', '12345').error, /9 números/);
assert.deepEqual(validarDocumento('cedula', '001-1234567-8'), { tipo: 'cedula', numero: '00112345678' });
assert.match(validarDocumento('cedula', '123').error, /11 números/);
assert.equal(validarDocumento('dni', 'ab-12345').numero, 'AB12345');
assert.deepEqual(validarDocumento('rnc', '  '), { tipo: null, numero: null }, 'sin número no hay documento');
assert.match(validarDocumento('', '12345678').error, /tipo/);
assert.equal(textoDocumento('cedula', '00112345678'), 'Cédula 001-1234567-8');
assert.equal(formatearDocumento('rnc', '101123456'), '101-12345-6');
console.log('  ✔ el RNC, la cédula y el DNI se validan y se muestran con su formato');
console.log('  ✔ la búsqueda de módulos ignora acentos y mayúsculas, usa palabras relacionadas y respeta los permisos');
process.exit(0);
